import { expect, it } from 'vitest';
import { formatDecimalRatioPercent } from '../src/ratio-percent.js';
it.each([
  ['0.25', '25%'],
  ['0.123456', '12.346%'],
  ['0.01000499999999999999999', '1%'],
  ['0.01000500000000000000001', '1.001%'],
  ['10', '1,000%'],
  ['1234.56789', '123,456.789%'],
  ['0', '0%'],
  ['-0', '0%'],
  ['0.000001', '1E-4%'],
  ['-0.000001', '-1E-4%'],
  ['0.000005', '0.001%'],
  ['0.' + '0'.repeat(399) + '1', '1E-398%'],
  ['1' + '0'.repeat(400), '1E402%'],
  ['1e1000000', '1E1000002%'],
  ['9.9999995e30', '1E33%'],
  ['bad', '—'],
  [null, '—'],
])('三位摘要 %s 显示 %s', (ratio, expected) =>
  expect(formatDecimalRatioPercent(ratio, 3)).toBe(expected),
);

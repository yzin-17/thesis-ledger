import { describe, expect, it } from 'vitest';
import { formatDecimalNumber } from '../src/decimal-number-display.js';
describe('十进制只读数字的有效数字和单位', () => {
  it.each([
    ['1234.123456789', '1,234.123457'],
    ['9007199254740993.1234564999999999999', '9,007,199,254,740,993.123456'],
    ['-9007199254740993.1234564999999999999', '-9,007,199,254,740,993.123456'],
    ['1.23456749999999999999999', '1.234567'],
    ['1.23456750000000000000001', '1.234568'],
    ['-1.23456749999999999999999', '-1.234567'],
    ['-1.23456750000000000000001', '-1.234568'],
    ['0.00000049999999999999999', '5E-7'],
    ['0.0000005', '0.000001'],
    ['0.' + '0'.repeat(399) + '1', '1E-400'],
    ['-0.' + '0'.repeat(399) + '1', '-1E-400'],
    ['1' + '0'.repeat(400), '1E400'],
    ['9.9999999e99', '1E100'],
    ['-9.9999999e99', '-1E100'],
    ['9.9999999e99999999999999999', '1E100000000000000000'],
    ['1e-99999999999999999999999', '1E-99999999999999999999999'],
    ['1e21', '1E21'],
    ['999999999999999999999', '999,999,999,999,999,999,999'],
    [' +0012.3400e-1 ', '1.234'],
    ['-.0000000001', '-1E-10'],
  ])('原文 %s 显示 %s', (value, expected) => {
    expect(formatDecimalNumber(value)).toBe(expected);
  });
  it.each([
    ['1.25', 'auto', '1.25'],
    ['1.25', 'always', '+1.25'],
    ['1.25', 'exceptZero', '+1.25'],
    ['-1.25', 'auto', '-1.25'],
    ['-1.25', 'always', '-1.25'],
    ['-1.25', 'exceptZero', '-1.25'],
    ['0', 'auto', '0'],
    ['0', 'always', '+0'],
    ['0', 'exceptZero', '0'],
    ['-0.00', 'auto', '0'],
    ['-0.00', 'always', '+0'],
    ['-0.00', 'exceptZero', '0'],
    ['1e-400', 'exceptZero', '+1E-400'],
    ['-1e-400', 'exceptZero', '-1E-400'],
    ['1e400', 'exceptZero', '+1E400'],
    ['-1e400', 'exceptZero', '-1E400'],
  ] as const)('符号 %s / %s', (value, sign, expected) => {
    expect(formatDecimalNumber(value, sign)).toBe(expected);
  });
  it.each(['0.000', '+0', '-0e99999999999999999', '.00000'])('零值 %s 不带负号', (value) => {
    expect(formatDecimalNumber(value)).toBe('0');
  });
  it.each([
    undefined,
    null,
    '',
    ' ',
    'NaN',
    'Infinity',
    '-Infinity',
    '1%',
    '1,234',
    '1e',
    '.',
    '--1',
    '0x10',
  ])('不可用 %s', (value) => {
    expect(formatDecimalNumber(value)).toBe('—');
    expect(formatDecimalNumber(value, 'always')).toBe('—');
  });
});

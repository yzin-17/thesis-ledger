import { expect, it } from 'vitest';
import { formatDecimalRatioPercent, formatRatioPercent } from '../src/ratio-percent.js';
it.each([
  [null, '—'],
  [undefined, '—'],
  ['', '—'],
  [' ', '—'],
  ['NaN', '—'],
  ['Infinity', '—'],
  ['0x1', '—'],
  ['1_000', '—'],
  ['1,2', '—'],
  ['1e', '—'],
  ['--1', '—'],
  ['0', '0.00%'],
  ['-0.0', '0.00%'],
  ['+0000.000', '0.00%'],
  ['0.0100499999999999999999999', '1.00%'],
  ['0.0100500000000000000000001', '1.01%'],
  ['-0.0100500000000000000000001', '-1.01%'],
  ['  +.5  ', '50.00%'],
  ['1.', '100.00%'],
  ['1.2345E-2', '1.23%'],
  ['+001.005E-2', '1.01%'],
  ['1e+0002', '10000.00%'],
  ['1e-400', '1E-398%'],
  ['-1e-400', '-1E-398%'],
  ['1e400', '1E402%'],
  ['-1e400', '-1E402%'],
  ['1e1000000', '1E1000002%'],
  ['1e-1000000', '1E-999998%'],
  ['9.9999995e-400', '1E-397%'],
  ['99999995000000000000', '1E22%'],
  ['0.000049999999999999999', '5E-3%'],
  ['0.' + '0'.repeat(399) + '1', '1E-398%'],
] as const)('文本比例 %s 展示为 %s', (value, expected) => {
  expect(formatDecimalRatioPercent(value)).toBe(expected);
});
it.each([
  ['0.01', '1%'],
  ['10', '1,000%'],
  ['0', '0%'],
  ['-0.01', '-1%'],
  ['0.33333333333333333333', '33.333333%'],
  ['.000012345678901234', '0.001235%'],
  ['.00000000001234', '1.234E-9%'],
  ['.1234567890123', '12.345679%'],
  ['1e-400', '1E-398%'],
] as const)('费率 %s 保留最多六位 %s', (value, expected) => {
  expect(formatDecimalRatioPercent(value, 6)).toBe(expected);
});
it('number 公共合同保持普通、临界与极值的既有结果', () => {
  expect(formatRatioPercent(0.01005)).toBe('1.01%');
  expect(formatRatioPercent(Number.MAX_VALUE)).toBe('1.797693E310%');
  expect(formatRatioPercent(Number.MIN_VALUE)).toBe('5E-322%');
  expect(formatRatioPercent(-0)).toBe('0.00%');
});
